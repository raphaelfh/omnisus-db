"""Render the dataset registry as docs/datasets.md.

The registry already knows every dataset's prefix, FTP directory, cadence,
partitioning and coverage. Writing that into hand-maintained per-dataset pages
means the same fact lives in two places and the docs drift (spec I4, §7.3):
today ``docs/sources/`` describes 5 datasets while the registry has 11.

Run with ``--check`` to fail when the committed file is stale — the same
pattern as ``ruff format --check``. The file is committed, so the docs build
stays a plain ``mkdocs build`` with no extra plugin.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from omnisus_db.sources.datasus_ftp.datasets import REGISTRY

OUT = Path(__file__).resolve().parent.parent / "docs" / "datasets.md"

HEADER = """<!-- Generated by scripts/gen_datasets_doc.py. Do not edit by hand. -->

# Datasets

Every dataset below is one row in the registry
(`src/omnisus_db/sources/datasus_ftp/datasets.py`). Adding a dataset is one
row, one `data/dicionarios/<name>.yaml`, and one test fixture — the CLI, the
Python API, the inventory and this page all follow from it.

Use the name or any alias wherever a dataset is accepted:

```bash
omnisus-db inventory <name>          # what the server actually publishes
omnisus-db import <name> --plan inventory --years 2020-2024
```

"""

FOOTER = """
Coverage is `(first, last)` as published upstream; **ongoing** means no end
bound. These bounds are checked against the live server every week by the
Tier 3 probe (`tests/integration/test_registry_probe.py`), so a row that
drifts from reality fails CI rather than misleading a caller.
"""


def render() -> str:
    rows = [
        "| Dataset | Aliases | Prefix | Cadence | Partitioned by | Coverage | FTP directory |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(REGISTRY):
        d = REGISTRY[name]
        first, last = d.coverage
        first_s = f"{first[0]}-{first[1]:02d}"
        last_s = "ongoing" if last is None else f"{last[0]}-{last[1]:02d}"
        aliases = ", ".join(f"`{a}`" for a in d.aliases) or "—"
        parts = ", ".join(f"`{c}`" for c in d.partition_by) or "—"
        rows.append(
            f"| `{d.name}` | {aliases} | `{d.prefix}` | {d.cadence} | {parts} | "
            f"{first_s} → {last_s} | `{d.ftp_dir}` |"
        )
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file differs from what the registry renders",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(
                f"{OUT} is stale. Run: uv run python scripts/gen_datasets_doc.py", file=sys.stderr
            )
            return 1
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT} ({len(REGISTRY)} datasets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
